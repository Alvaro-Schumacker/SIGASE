CREATE TABLE IF NOT EXISTS public.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('aditamento', 'pernoite', 'fatd', 'prorrogacao')),
    bulletin_number TEXT NOT NULL,
    document_date TEXT NOT NULL,
    data_json TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.force_maps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_date TEXT NOT NULL,
    data_json TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.vacation_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES public.unit_personnel(id),
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    travel_days INTEGER NOT NULL DEFAULT 0 CHECK (travel_days IN (0, 1)),
    vacation_days INTEGER NOT NULL,
    presentation_date TEXT NOT NULL,
    period_number INTEGER NOT NULL CHECK (period_number BETWEEN 1 AND 3),
    period_total INTEGER NOT NULL CHECK (period_total BETWEEN 1 AND 3),
    reference_year INTEGER NOT NULL DEFAULT 2026 CHECK (reference_year IN (2025, 2026)),
    task_added INTEGER NOT NULL DEFAULT 0 CHECK (task_added IN (0, 1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.duty_scales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    mode TEXT NOT NULL CHECK (mode IN ('corrida', 'preta_vermelha', 'completa')),
    services_json TEXT NOT NULL,
    participants_json TEXT NOT NULL,
    assignments_json TEXT NOT NULL DEFAULT '{}',
    red_dates_json TEXT NOT NULL DEFAULT '[]',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    subject TEXT NOT NULL,
    notice_date TEXT NOT NULL,
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    category TEXT NOT NULL DEFAULT 'geral',
    source_type TEXT,
    source_id BIGINT
);

CREATE TABLE IF NOT EXISTS public.notice_recipients (
    notice_id BIGINT NOT NULL REFERENCES public.notices(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    acknowledged_at TIMESTAMPTZ,
    PRIMARY KEY (notice_id, user_id)
);

