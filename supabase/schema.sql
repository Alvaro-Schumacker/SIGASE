ALTER TABLE public.unit_personnel ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.force_maps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vacation_plan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.duty_scales ENABLE ROW LEVEL SECURITY;
