-- SIGASE schema for a dedicated Supabase project.
-- Run this once in Supabase SQL Editor before starting the local Python server.

CREATE TABLE IF NOT EXISTS public.app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name TEXT NOT NULL,
    login TEXT,
    password_hash TEXT,
    role TEXT NOT NULL CHECK (role IN ('viewer', 'editor', 'admin')),
    functions_json TEXT NOT NULL DEFAULT '[]',
    avatar_icon TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_app_users_display_name_lower ON public.app_users (LOWER(display_name));
CREATE UNIQUE INDEX IF NOT EXISTS idx_app_users_login_lower ON public.app_users (LOWER(login)) WHERE login IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.task_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_task_categories_name_lower ON public.task_categories (LOWER(name));

CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    classification TEXT NOT NULL DEFAULT '',
    requester_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    assignee_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    priority TEXT NOT NULL CHECK (priority IN ('Baixa', 'Média', 'Alta')),
    due_date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pendente' CHECK (status IN ('Pendente', 'Em andamento', 'Concluída')),
    events_json TEXT NOT NULL DEFAULT '[]',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_tasks_assignee ON public.tasks (assignee_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tasks_requester ON public.tasks (requester_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.user_sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS public.personnel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    rank TEXT NOT NULL,
    function TEXT NOT NULL,
    section TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Ativo',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.unit_personnel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    war_name TEXT NOT NULL,
    birth_date TEXT NOT NULL,
    rank TEXT NOT NULL,
    qm TEXT NOT NULL,
    section TEXT NOT NULL,
    address TEXT NOT NULL,
    cpf TEXT NOT NULL,
    military_id TEXT NOT NULL,
    military_number TEXT NOT NULL DEFAULT '',
    seniority_order INTEGER,
    additional_data TEXT NOT NULL DEFAULT '',
    civil_id TEXT NOT NULL DEFAULT '',
    prec_cp TEXT NOT NULL DEFAULT '',
    blood_type TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    religion TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    birth_city TEXT NOT NULL DEFAULT '',
    mother_name TEXT NOT NULL DEFAULT '',
    father_name TEXT NOT NULL DEFAULT '',
    cnh TEXT NOT NULL DEFAULT '',
    education TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

