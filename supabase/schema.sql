-- SIGASE schema for a dedicated Supabase project.
-- Run this once in Supabase SQL Editor before starting the local Python server.

CREATE TABLE IF NOT EXISTS public.app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name TEXT NOT NULL,
    login TEXT,
    password_hash TEXT,
    role TEXT NOT NULL CHECK (role IN ('viewer', 'editor', 'admin')),
    functions_json TEXT NOT NULL DEFAULT '[]',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_app_users_display_name_lower ON public.app_users (LOWER(display_name));
CREATE UNIQUE INDEX IF NOT EXISTS idx_app_users_login_lower ON public.app_users (LOWER(login)) WHERE login IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.task_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_task_categories_name_lower ON public.task_categories (LOWER(name));

CREATE TABLE IF NOT EXISTS public.user_sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS public.personnel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    rank TEXT NOT NULL,
    function TEXT NOT NULL,
    section TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Ativo',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.unit_personnel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    war_name TEXT NOT NULL,
    birth_date TEXT NOT NULL,
    rank TEXT NOT NULL,
    qm TEXT NOT NULL,
    section TEXT NOT NULL,
    address TEXT NOT NULL,
    cpf TEXT NOT NULL,
    military_id TEXT NOT NULL,
    additional_data TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('aditamento', 'pernoite', 'fatd')),
    bulletin_number TEXT NOT NULL,
    document_date TEXT NOT NULL,
    data_json TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.force_maps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_date TEXT NOT NULL,
    data_json TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.vacation_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES public.unit_personnel(id),
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    travel_days INTEGER NOT NULL DEFAULT 0 CHECK (travel_days IN (0, 1)),
    vacation_days INTEGER NOT NULL,
    presentation_date TEXT NOT NULL,
    period_number INTEGER NOT NULL CHECK (period_number BETWEEN 1 AND 3),
    period_total INTEGER NOT NULL CHECK (period_total BETWEEN 1 AND 3),
    task_added INTEGER NOT NULL DEFAULT 0 CHECK (task_added IN (0, 1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.duty_scales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    mode TEXT NOT NULL CHECK (mode IN ('corrida', 'preta_vermelha', 'completa')),
    services_json TEXT NOT NULL,
    participants_json TEXT NOT NULL,
    assignments_json TEXT NOT NULL DEFAULT '{}',
    red_dates_json TEXT NOT NULL DEFAULT '[]',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    subject TEXT NOT NULL,
    notice_date TEXT NOT NULL,
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    category TEXT NOT NULL DEFAULT 'geral',
    source_type TEXT,
    source_id BIGINT
);

CREATE TABLE IF NOT EXISTS public.notice_recipients (
    notice_id BIGINT NOT NULL REFERENCES public.notices(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    acknowledged_at TIMESTAMPTZ,
    PRIMARY KEY (notice_id, user_id)
);

