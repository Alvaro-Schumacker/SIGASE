CREATE OR REPLACE FUNCTION public.sigase_audit_row() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_new JSONB;
  v_old JSONB;
  v_row JSONB;
  v_actor_id BIGINT;
  v_actor_name TEXT;
  v_action TEXT;
  v_entity TEXT;
  v_label TEXT;
  v_id TEXT;
BEGIN
  v_actor_id := NULLIF(current_setting('sigase.actor_id', true), '')::BIGINT;
  IF v_actor_id IS NULL THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
  END IF;
  v_actor_name := COALESCE(NULLIF(current_setting('sigase.actor_name', true), ''), 'Usuário');
  v_action := CASE TG_OP WHEN 'INSERT' THEN 'criou' WHEN 'UPDATE' THEN 'editou' ELSE 'excluiu' END;
  v_entity := CASE TG_TABLE_NAME
    WHEN 'app_users' THEN 'usuário' WHEN 'task_categories' THEN 'classificação'
    WHEN 'tasks' THEN 'tarefa' WHEN 'personnel' THEN 'usuário interno'
    WHEN 'unit_personnel' THEN 'militar do efetivo' WHEN 'documents' THEN 'documento'
    WHEN 'force_maps' THEN 'Mapa da Força' WHEN 'vacation_plan' THEN 'período de férias'
    WHEN 'duty_scales' THEN 'escala de serviço' WHEN 'notices' THEN 'aviso'
    WHEN 'notice_recipients' THEN 'destinatários de aviso' WHEN 'task_assignees' THEN 'responsáveis da tarefa'
    ELSE TG_TABLE_NAME END;
  v_new := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) ELSE NULL END;
  v_old := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) ELSE NULL END;
  v_row := COALESCE(v_new, v_old);
  v_id := COALESCE(v_row->>'id', v_row->>'task_id', v_row->>'notice_id', v_row->>'person_id', '');
  v_label := CASE TG_TABLE_NAME
    WHEN 'app_users' THEN COALESCE(v_row->>'display_name', '')
    WHEN 'task_categories' THEN COALESCE(v_row->>'name', '')
    WHEN 'tasks' THEN COALESCE(v_row->>'title', '')
    WHEN 'personnel' THEN COALESCE(v_row->>'name', '')
    WHEN 'unit_personnel' THEN COALESCE(v_row->>'full_name', '')
    WHEN 'documents' THEN concat_ws(' ', COALESCE(v_row->>'kind','documento'), 'Nr', COALESCE(v_row->>'bulletin_number', ''))
    WHEN 'force_maps' THEN concat('em ', COALESCE(v_row->>'activity_date', ''))
    WHEN 'vacation_plan' THEN concat('período Nr ', COALESCE(v_row->>'id', ''))
    WHEN 'duty_scales' THEN COALESCE(v_row->>'name', '')
    WHEN 'notices' THEN COALESCE(v_row->>'title', '')
    ELSE COALESCE(v_id, '') END;
  INSERT INTO public.audit_log(actor_id, actor_name, action, entity, entity_label)
  VALUES (v_actor_id, v_actor_name, v_action, v_entity,
          concat_ws(' ', NULLIF(v_label, ''), CASE WHEN TG_TABLE_NAME <> 'documents' AND NULLIF(v_id, '') IS NOT NULL THEN concat('(Nr ', v_id, ')') END));
  IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;

DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['app_users','task_categories','tasks','task_assignees','personnel','unit_personnel','documents','force_maps','vacation_plan','duty_scales','notices','notice_recipients'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS sigase_audit_change ON public.%I', t);
    EXECUTE format('CREATE TRIGGER sigase_audit_change AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.sigase_audit_row()', t);
  END LOOP;
END;
$$;

REVOKE ALL ON public.audit_log FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.audit_log_id_seq FROM anon, authenticated;
REVOKE ALL ON FUNCTION public.sigase_audit_row() FROM PUBLIC, anon, authenticated;
